const BRANCH_ORDER = ["子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"];
const CLASH: Record<string, string> = {
  子: "午", 午: "子", 丑: "未", 未: "丑", 寅: "申", 申: "寅",
  卯: "酉", 酉: "卯", 辰: "戌", 戌: "辰", 巳: "亥", 亥: "巳",
};
const SIX_HARMONY: Record<string, string> = {
  子: "丑", 丑: "子", 寅: "亥", 亥: "寅", 卯: "戌", 戌: "卯",
  辰: "酉", 酉: "辰", 巳: "申", 申: "巳", 午: "未", 未: "午",
};
const THREE_HARMONY = ["申子辰", "亥卯未", "寅午戌", "巳酉丑"];

/** 2027년 양력 1~12월의 달 지지. 1월은 절기상 아직 2026년의 축(丑)월이다 */
const MONTH_BRANCHES_2027 = ["丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥", "子"];

/** 띠 지지와 각 달 지지의 충·합으로 좋은 달·조심할 달을 고른다 */
export function zodiacMonths(branch: string): { good: number[]; caution: number[] } {
  const good: number[] = [];
  const caution: number[] = [];
  MONTH_BRANCHES_2027.forEach((mb, i) => {
    const month = i + 1;
    if (CLASH[branch] === mb) caution.push(month);
    else if (mb !== branch && (SIX_HARMONY[branch] === mb || THREE_HARMONY.some((g) => g.includes(branch) && g.includes(mb)))) {
      good.push(month);
    }
  });
  return { good, caution };
}

/** 그 띠의 출생 연도와 2027년 연 나이(2027 − 출생 연도, 1930~2026년생) */
export function zodiacBirthYears(branch: string): { year: number; age: number }[] {
  const index = BRANCH_ORDER.indexOf(branch);
  const out: { year: number; age: number }[] = [];
  for (let y = 1930; y <= 2026; y += 1) {
    if ((((y - 4) % 12) + 12) % 12 === index) out.push({ year: y, age: 2027 - y });
  }
  return out.reverse();
}

export function findZodiac(slug: string): Zodiac2027 | undefined {
  return ZODIAC_2027.find((z) => z.slug === slug);
}
