/** 팝업용 글자 버전 */
export function privacyPlainText(): string {
  const parts = ["개인정보처리방침"];
  for (const s of PRIVACY_SECTIONS) {
    const lines = [s.title];
    if (s.paragraphs) lines.push(...s.paragraphs);
    if (s.bullets) lines.push(...s.bullets.map((b) => `- ${b}`));
    if (s.table) {
      for (const row of s.table.rows) lines.push(`- ${row[0]}: ${row[1]} → ${row[2]}`);
    }
    parts.push(lines.join("\n"));
  }
  parts.push(`시행일: ${PRIVACY_EFFECTIVE_DATE}`);
  return parts.join("\n\n");
}
